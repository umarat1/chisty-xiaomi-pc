enum Tier { recommended, optional, risky, protectedHard }

extension TierText on Tier {
  String get title => switch (this) {
    Tier.recommended => 'Рекомендуется',
    Tier.optional => 'Опционально',
    Tier.risky => 'Опасно',
    Tier.protectedHard => 'Критично для системы',
  };
}

class Pkg {
  const Pkg(this.id, this.title, this.desc, this.tier, {this.telemetry = false});
  final String id, title, desc;
  final Tier tier;
  final bool telemetry;
}

Pkg r(String id, String t, String d, {bool tel = false}) => Pkg(id, t, d, Tier.recommended, telemetry: tel);
Pkg o(String id, String t, String d) => Pkg(id, t, d, Tier.optional);
Pkg x(String id, String t, String d) => Pkg(id, t, d, Tier.risky);
Pkg p(String id, String t, String d) => Pkg(id, t, d, Tier.protectedHard);

